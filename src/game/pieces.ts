export function kicksFor(type: PieceId, from: number, to: number): [number, number][] {
  if (type === "O") return [[0, 0]];
  const key = `${from}>${to}`;
  const table = type === "I" ? I_KICKS : JLSTZ_KICKS;
  return table[key] ?? [[0, 0]];
}

export function cellsOf(type: PieceId, rot: number): number[][] {
  return SHAPES[type][rot]!;
}

export function spawnX(type: PieceId): number {
  return type === "O" ? 4 : 3;
}

